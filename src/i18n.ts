export const DICTS: Record<Lang, Dict> = { en, es };

export interface I18n {
  lang: Lang;
  t: (key: Key, vars?: Record<string, string | number>) => string;
  l: (text: Localized) => string;
}

export function makeI18n(lang: Lang): I18n {
  const dict = DICTS[lang];
  return {
    lang,
    t: (key, vars) => {
      let s = dict[key] ?? en[key] ?? key;
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
      return s;
    },
    l: (text) => text[lang] ?? text.en,
  };
}

export const I18nContext = createContext<I18n>(makeI18n('en'));

export function useI18n(): I18n {
  return useContext(I18nContext);
}

export function detectLang(): Lang {
  const param = typeof location !== 'undefined' ? new URLSearchParams(location.search).get('lang') : null;
  if (param === 'en' || param === 'es') return param;
  try {
    const saved = localStorage.getItem('meltpoint:lang');
    if (saved === 'en' || saved === 'es') return saved;
  } catch {
    // Storage can be unavailable; fall through to the browser language.
  }
  return typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('es') ? 'es' : 'en';
}
